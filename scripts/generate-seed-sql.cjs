/**
 * Writes supabase/seed.sql from src/lib/data/seed.ts, so the Supabase seed and
 * the local store's seed can never drift apart.
 *
 * Usage (from the repo root): node scripts/generate-seed-sql.cjs
 */
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "src/lib/data/seed.ts"), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText;

const seedModule = { exports: {} };
new Function("module", "exports", "require", compiled)(seedModule, seedModule.exports, require);
const { SEED_PROJECTS, SEED_SKILLS } = seedModule.exports;

const DELIMITER = "$md$";
const quote = (value) =>
  value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`;
const array = (items) => (items.length ? `array[${items.map(quote).join(", ")}]` : "'{}'::text[]");
const markdown = (value) => {
  if (value.includes(DELIMITER)) throw new Error("Markdown contains the dollar-quote delimiter.");
  return `${DELIMITER}${value}${DELIMITER}`;
};

const projects = SEED_PROJECTS.map(
  (project) => `  (
    ${quote(project.id)},
    ${quote(project.title)},
    ${quote(project.slug)},
    ${quote(project.category)},
    ${quote(project.summary)},
    ${markdown(project.description_markdown)},
    ${array(project.tech_stack)},
    ${quote(project.thumbnail_url)},
    ${array(project.gallery_urls)},
    ${quote(project.demo_url)},
    ${quote(project.github_url)},
    ${project.featured},
    ${quote(project.created_at)},
    ${quote(project.updated_at)}
  )`,
).join(",\n");

const skills = SEED_SKILLS.map(
  (skill) =>
    `  (${quote(skill.id)}, ${quote(skill.name)}, ${quote(skill.category)}, ${skill.proficiency}, ${quote(skill.icon_name)}, ${skill.display_order})`,
).join(",\n");

const sql = `-- ===========================================================================
-- Ardmst — seed.sql
-- The real portfolio content: two projects and the toolbox.
--
-- GENERATED by scripts/generate-seed-sql.cjs from src/lib/data/seed.ts (the
-- local store's seed). Edit that file and regenerate; do not edit this one.
--
-- Run AFTER migrations/01_schema.sql. Running it again changes nothing.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- projects
-- ---------------------------------------------------------------------------
insert into public.projects
  (id, title, slug, category, summary, description_markdown, tech_stack, thumbnail_url, gallery_urls, demo_url, github_url, featured, created_at, updated_at)
values
${projects}
on conflict do nothing;

-- ---------------------------------------------------------------------------
-- skills (the toolbox)
--
-- The schema needs a proficiency number. Every tool carries the same neutral
-- value and the public site never shows it.
-- ---------------------------------------------------------------------------
insert into public.skills (id, name, category, proficiency, icon_name, display_order)
values
${skills}
on conflict do nothing;

-- messages: none. The inbox starts empty.
`;

fs.writeFileSync(path.join(root, "supabase/seed.sql"), sql);
console.log(`supabase/seed.sql written: ${SEED_PROJECTS.length} projects, ${SEED_SKILLS.length} skills.`);
